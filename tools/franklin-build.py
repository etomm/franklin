#!/usr/bin/env python3
"""Franklin separable build planner.

Reads docs/features/manifest.json (generated by tools/feature-catalog.py),
resolves dependencies, and produces a deterministic build order.

Guarantees separability: if you exclude a feature with --without, the planner
fails if any remaining selected feature depends on it (transitively), so you
know immediately that removing it would break something.

Usage:
  tools/franklin-build.py --plan                 # print resolved build order
  tools/franklin-build.py --all --check          # validate full graph
  tools/franklin-build.py --features cake-qos,tee
  tools/franklin-build.py --all --without adaptive-qos --plan
  tools/franklin-build.py --features web-ui --run # run per-feature build.sh if present

Convention: a feature may provide features/<id>/build.sh and install.sh.
If --run is given, those are executed in build order; otherwise only planned.
"""
import argparse, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MANIFEST = os.path.join(ROOT, "docs", "features", "manifest.json")


def load():
    with open(MANIFEST, encoding="utf-8") as fh:
        m = json.load(fh)
    feats = {f["id"]: f for f in m["features"]}
    return m, feats


def deps_closure(sel, feats):
    """Return selected plus all transitive dependencies."""
    out = set()
    stack = list(sel)
    while stack:
        i = stack.pop()
        if i in out:
            continue
        out.add(i)
        for d in feats.get(i, {}).get("depends_on", []):
            if d not in feats:
                raise SystemExit("unknown dependency '%s' required by '%s'" % (d, i))
            stack.append(d)
    return out


def topo(sel, feats, order):
    s = set(sel)
    return [i for i in order if i in s]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=MANIFEST)
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--features", default="")
    ap.add_argument("--without", default="")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--plan", action="store_true")
    args = ap.parse_args()

    m, feats = load()
    total_order = m["build_order"]

    if args.all:
        sel = set(feats) if len(sys.argv) > 1 else set()
        selected = set(feats)
    elif args.features:
        selected = {x.strip() for x in args.features.split(",") if x.strip()}
    else:
        selected = set(feats)  # default: everything (same as --all)

    unknown = [x for x in selected if x not in feats]
    if unknown:
        raise SystemExit("unknown feature(s): %s" % ", ".join(unknown))

    without = {x.strip() for x in args.without.split(",") if x.strip()}
    unknown_w = [x for x in without if x not in feats]
    if unknown_w:
        raise SystemExit("unknown --without feature(s): %s" % ", ".join(unknown_w))

    # required features cannot be removed
    removed_required = [x for x in without if feats[x].get("required")]
    if removed_required:
        raise SystemExit("cannot remove required feature(s): %s" % ", ".join(removed_required))

    selected = deps_closure(selected, feats) - without

    # separability check: selected features must not depend on removed ones
    broken = []
    for i in selected:
        for d in feats[i].get("depends_on", []):
            if d in without:
                broken.append((i, d))
    if broken:
        msg = []
        for i, d in broken:
            msg.append("  %s depends on removed %s" % (i, d))
        raise SystemExit("removing these breaks selected features:\n" + "\n".join(msg))

    if args.check:
        print("OK: %d features selected, graph consistent" % len(selected))
        return

    order = topo(selected, feats, total_order)
    print("Resolved build order (%d features):" % len(order))
    for n, i in enumerate(order, 1):
        req = " [required]" if feats[i].get("required") else ""
        step = ""
        bsh = os.path.join(ROOT, "features", i, "build.sh")
        if os.path.exists(bsh):
            step = " (build.sh)"
        print("  %2d. %s%s%s" % (n, i, req, step))

    if args.run:
        print("\nRunning per-feature build.sh where present...")
        for i in order:
            bsh = os.path.join(ROOT, "features", i, "build.sh")
            if os.path.exists(bsh):
                print("--- %s ---" % i)
                r = os.system("sh %s" % bsh)
                if r != 0:
                    raise SystemExit("build failed: %s" % i)


if __name__ == "__main__":
    main()
