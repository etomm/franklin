#!/usr/bin/env python3
"""Audit which features are really gnuton features (reproducible "triple check").

Compares an extracted stock ASUSWRT rootfs with an extracted gnuton rootfs and
answers one question per feature: does gnuton ship something stock does not?

Rules used for the plan kinds:
  * page/binary only in gnuton  -> gnuton-feature (or a workaround if it is a
                                   Franklin mechanism, e.g. boot hook)
  * present in both rootfs      -> stock (gnuton inherited it)
  * present in neither          -> franklin-feature (or proprietary, if the
                                   vendor ships a closed component)

Usage:
  python tools/parity-audit.py \
      --stock  firmware/xt8/rootfs \
      --gnuton firmware/gnuton-xt8/rootfs \
      --out docs/parity-audit.md

Extraction: see docs/firmware-comparison.md (ubireader + unsquashfs).
"""
import argparse
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

SCAN_DIRS = ("www", "usr/sbin", "sbin", "usr/bin", "bin", "lib/modules")

# feature probe -> page/binary needles (matched case-insensitively on basename)
PROBES = [
    ("web-ui pages", ["tools_sysinfo.asp", "advanced_vpndirector.asp", "wifi_insight.asp"]),
    ("VPN Director", ["advanced_vpndirector.asp"]),
    ("DNS Director", ["dnsdirector.asp"]),
    ("SNMP", ["advanced_snmp_content.asp", "snmpd"]),
    ("NFS", ["advanced_aidisk_nfs.asp", "nfsd"]),
    ("Tor", ["advanced_tor_content.asp", "tor"]),
    ("Wireless Survey", ["advanced_wireless_survey.asp"]),
    ("Traffic Monitor (extra pages)", ["main_trafficmonitor_monthly.asp",
                                       "main_trafficmonitor_settings.asp"]),
    ("amtm", ["amtm"]),
    ("ipset tool", ["ipset"]),
    ("ntpd", ["ntpd"]),
    ("crontab", ["crontab"]),
    ("custom user pages", ["user1.asp", "user20.asp"]),
    ("JFFS upload page", ["uploadingjffs.asp"]),
    ("AiProtection", ["aiprotection_homeprotection.asp"]),
    ("Traffic Analyzer", ["trafficanalyzer_statistic.asp"]),
    ("Cloud sync", ["cloud_sync.asp"]),
    ("Firmware upgrade page", ["advanced_firmwareupgrade_content.asp"]),
    ("IPv6 pages", ["advanced_ipv6_content.asp"]),
    ("DHCP static leases", ["advanced_dhcp_content.asp"]),
    ("Parental controls", ["parentalcontrol.asp"]),
    ("Port forwarding", ["advanced_virtualserver_content.asp"]),
    ("USB modem", ["advanced_modem_content.asp"]),
    ("Operation modes", ["advanced_operationmode_content.asp"]),
    ("Wireless tuning", ["advanced_wireless_content.asp",
                         "advanced_smart_connect.asp", "advanced_wwps_content.asp"]),
    ("minidlna", ["minidlna"]),
    ("Time Machine", ["advanced_timemachine.asp"]),
    ("dropbear/SSH", ["dropbear"]),
    ("syslogd", ["syslogd"]),
    ("ebtables/MAC filter", ["ebtables"]),
    ("odhcp6c", ["odhcp6c"]),
    ("miniupnpd", ["miniupnpd"]),
    ("mount.cifs", ["mount.cifs"]),
    ("hdparm", ["hdparm"]),
    ("aria2", ["aria2c"]),
    ("smartctl", ["smartctl"]),
    ("AiMesh agent (amas)", ["amas_ipc"]),
    ("AiMesh config sync", ["cfg_server", "cfg_client"]),
    ("AiMesh UI", ["aimesh.asp"]),
    ("mesh wireless driver", ["dhd.ko"]),
]


def listing(root, sub):
    base = os.path.join(root, sub)
    out = set()
    if not os.path.isdir(base):
        return out
    for dirpath, _dirs, files in os.walk(base):
        rel = os.path.relpath(dirpath, base)
        for f in files:
            out.add(f if rel == "." else os.path.normpath(os.path.join(rel, f)))
    return out


def norm(s):
    return s.replace("\\", "/").lower()


def load(root):
    files = set()
    for sub in SCAN_DIRS:
        for f in listing(root, sub):
            files.add(norm(os.path.join(sub, f)))
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stock", default="firmware/xt8/rootfs")
    ap.add_argument("--gnuton", default="firmware/gnuton-xt8/rootfs")
    ap.add_argument("--out", default="docs/parity-audit.md")
    args = ap.parse_args()

    stock_dir = args.stock if os.path.isabs(args.stock) else os.path.join(ROOT, args.stock)
    gnuton_dir = args.gnuton if os.path.isabs(args.gnuton) else os.path.join(ROOT, args.gnuton)
    for d in (stock_dir, gnuton_dir):
        if not os.path.isdir(d):
            raise SystemExit("missing rootfs: %s (extract it first, see docs/firmware-comparison.md)" % d)

    g = load(gnuton_dir)
    s = load(stock_dir)
    only_g = sorted(g - s)
    only_s = sorted(s - g)

    out = []
    out.append("# Parity audit: is it a gnuton feature?\n")
    out.append("")
    out.append("Generated by `tools/parity-audit.py` by comparing an extracted stock")
    out.append("ASUSWRT rootfs with an extracted gnuton rootfs. Re-run it after downloading")
    out.append("new firmware to keep the feature kinds honest.\n")
    out.append("Method: a file that exists **only in gnuton** proves gnuton adds something;")
    out.append("a file in **both** proves the feature is stock ASUSWRT that gnuton merely")
    out.append("inherits. That is how each plan's `Kind` was chosen.\n")
    out.append("Directories compared: %s.\n" % ", ".join("`%s/`" % d for d in SCAN_DIRS))
    out.append("Totals: gnuton %d files, stock %d files, gnuton-only %d, stock-only %d.\n"
               % (len(g), len(s), len(only_g), len(only_s)))
    out.append("")
    out.append("## Feature probes\n")
    out.append("")
    out.append("| Probe | gnuton | stock | verdict |")
    out.append("|---|---|---|---|")
    for name, needles in PROBES:
        needles = [norm(n) for n in needles]
        ing = [n for n in needles if any(n == f or f.endswith("/" + n) for f in g)]
        ins = [n for n in needles if any(n == f or f.endswith("/" + n) for f in s)]
        if ing and not ins:
            verdict = "**gnuton-only** → gnuton feature"
        elif ing and ins:
            verdict = "in both → **stock** (not a gnuton feature)"
        else:
            verdict = "in neither → **franklin addition** (or proprietary)"
        out.append("| %s | %s | %s | %s |" % (
            name,
            ", ".join("`%s`" % x.split("/")[-1] for x in ing) or "—",
            ", ".join("`%s`" % x.split("/")[-1] for x in ins) or "—",
            verdict))
    out.append("")
    out.append("## Files present only in gnuton\n")
    out.append("")
    out.append("```")
    out.extend(only_g)
    out.append("```")
    out.append("")
    if only_s:
        out.append("## Files present only in stock\n")
        out.append("")
        out.append("Unexpected entries here usually mean gnuton dropped or renamed a stock")
        out.append("component.\n")
        out.append("```")
        out.extend(only_s)
        out.append("```")
        out.append("")

    path = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("wrote %s (%d gnuton-only files, %d stock-only)" % (path, len(only_g), len(only_s)))


if __name__ == "__main__":
    main()
