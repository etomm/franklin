#!/bin/sh
# Build the httpd shim and stage the companion.
#
#   src/shim.c        -> payload/opt/lib/gnuton/libfranklin_rc.so
#   actions/*.sh      -> actions.h (compiled action table) + payload/actions/
#
# The action table is generated here, from the handlers themselves, so the C
# shim never needs editing when a new rc action is implemented.
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
here=$(cd "$(dirname "$0")" && pwd)
cd "$here"

CC="${CROSS_COMPILE:-arm-linux-gnueabi-}gcc"
command -v "$CC" >/dev/null 2>&1 || {
    echo "missing cross compiler $CC (set CROSS_COMPILE=arm-linux-gnueabi-)" >&2
    exit 1
}

OUT="${OUT:-$ROOT/features/franklin-rc/payload}"
mkdir -p "$OUT/opt/lib/gnuton" "$OUT/bin" "$OUT/actions"

# 1. Action table from the handler filenames.
actions=$(cd actions && ls -1 *.sh 2>/dev/null | sed 's/\.sh$//' | LC_ALL=C sort || true)
[ -n "$actions" ] || {
    echo "no handlers in features/franklin-rc/actions/" >&2
    exit 1
}
{
    echo "/* generated by build.sh from the actions directory - do not edit */"
    echo "static const char *const franklin_actions[] = {"
    for a in $actions; do
        case "$a" in
            *[!a-z0-9_]*) echo "invalid action name: $a" >&2; exit 1 ;;
        esac
        echo "    \"$a\","
    done
    echo "    NULL"
    echo "};"
} >src/actions.h

# 2. The shim.
#    Linking against the host toolchain's libc stamps `dlsym@GLIBC_2.34` on the
#    reference, and the router runs glibc 2.26, where the shim would fail to
#    load. Link the `dlsym` reference against the *target's* libdl instead
#    (it exports dlsym@GLIBC_2.4); every other symbol here is older than 2.26.
STOCK_ROOTFS="${STOCK_ROOTFS:-$ROOT/firmware/xt8/rootfs}"
TARGET_LIBDL="$STOCK_ROOTFS/lib/libdl.so.2"
[ -f "$TARGET_LIBDL" ] || {
    echo "missing $TARGET_LIBDL (extract the stock firmware first)" >&2
    exit 1
}
"$CC" -shared -fPIC -O2 -Wall -Wextra -Werror \
    -nostdlib -o "$OUT/opt/lib/gnuton/libfranklin_rc.so" \
    src/shim.c "$TARGET_LIBDL" -lc -lgcc

# Fail the build, not the router, if a symbol demands a newer glibc than 2.26.
too_new=$(objdump -T "$OUT/opt/lib/gnuton/libfranklin_rc.so" | grep -oE 'GLIBC_[0-9]+\.[0-9]+' \
    | sort -uV | awk -F'[_.]' '$2 > 2 || ($2 == 2 && $3 > 26) { print }')
if [ -n "$too_new" ]; then
    echo "shim needs a newer glibc than the router (2.26): $too_new" >&2
    exit 1
fi

# 3. Handlers travel with the feature (private payload dir).
for a in $actions; do
    cp "actions/$a.sh" "$OUT/actions/$a.sh"
done

find "$OUT" -exec touch -d '@0' {} + 2>/dev/null || true

# Freshness stamp (same formula as tools/franklin-compose.py build_stamp()).
stamp=$( {
    printf '%s\0' build.sh;    cat "$here/build.sh";    printf '\0'
    printf '%s\0' feature.yaml; cat "$here/feature.yaml"; printf '\0'
} | sha256sum | cut -d' ' -f1 )
printf '%s\n' "$stamp" > "$OUT/.build-stamp"

echo "staged $OUT: shim + $(printf '%s\n' $actions | wc -l) action(s); table: $(printf '%s ' $actions)"
